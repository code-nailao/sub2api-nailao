const UpstreamRejectionRequestIDPrefix = "upstream-rejection:"

const (
	UpstreamRejectionReserved = "reserved"
	UpstreamRejectionSent     = "sent"
	UpstreamRejectionUnknown  = "unknown"
	UpstreamRejectionRejected = "rejected"
	UpstreamRejectionReleased = "released"
	UpstreamRejectionNormal   = "normal"
)

var (
	ErrUpstreamRejectionInvalid                  = errors.New("invalid upstream rejection billing command")
	ErrUpstreamRejectionNotFound                 = errors.New("upstream rejection reservation not found")
	ErrUpstreamRejectionConflict                 = errors.New("upstream rejection reservation conflict")
	ErrUpstreamRejectionState                    = errors.New("invalid upstream rejection billing transition")
	ErrUpstreamRejectionIntegrity                = errors.New("upstream rejection hold integrity failure")
	ErrUpstreamRejectionPlatformQuotaUnsupported = errors.New("upstream rejection billing does not support configured Grok platform quotas")
	// ErrUpstreamRejectionWaived reports a result for a hold that the deadline
	// waiver already released. The result was recorded for supplier
	// reconciliation and must not be charged, retried or treated as a failure.
	ErrUpstreamRejectionWaived = errors.New("upstream rejection hold already released at its deadline; late result recorded without charge")
)

// Release-deadline policy for synchronous requests whose outcome stays unknown:
// the site releases the hold and absorbs any upstream cost. The gateway has no
// total-duration limit for a request, so the max lifetime is a policy bound
// for a sent request whose process died before it could record an outcome,
// not a guarantee that no request runs longer. Deadlines are always computed
// and compared with the database clock.
const (
	UpstreamRejectionMaxRequestLifetime = 30 * time.Minute
	UpstreamRejectionReleaseGrace       = 10 * time.Minute
)

// UpstreamRejectionReleaseDeadlinePassed is the evidence reason of a release
// by the deadline waiver. A release confirmed by the upstream has no reason,
// which keeps its evidence and fingerprint identical to earlier releases.
const UpstreamRejectionReleaseDeadlinePassed = "deadline_passed"

// UpstreamRejectionReserveCommand is a write-once price and identity snapshot.
// RequestID must be generated by the server, never copied from a client header.
// Price is the exact customer fixed fee; no multiplier is applied by this module.
type UpstreamRejectionReserveCommand struct {
	RequestID            string  `json:"request_id"`
	UserID               int64   `json:"user_id"`
	APIKeyID             int64   `json:"api_key_id"`
	AccountID            int64   `json:"account_id"`
	GroupID              int64   `json:"group_id"`
	Model                string  `json:"model"`
	RequestPayloadHash   string  `json:"request_payload_hash"`
	UpstreamIdentityHash string  `json:"upstream_identity_hash"`
	PolicyVersion        string  `json:"policy_version"`
	RuleVersion          string  `json:"rule_version"`
	ProviderProfile      string  `json:"provider_profile"`
	Price                float64 `json:"price"`
	UpstreamCost         float64 `json:"upstream_cost"`
	UpstreamCurrency     string  `json:"upstream_currency"`
}

func NewUpstreamRejectionRequestID() string {
	return UpstreamRejectionRequestIDPrefix + uuid.NewString()
}

func IsUpstreamRejectionRequestID(value string) bool {
	if !strings.HasPrefix(value, UpstreamRejectionRequestIDPrefix) {
		return false
	}
	id, err := uuid.Parse(strings.TrimPrefix(value, UpstreamRejectionRequestIDPrefix))
	return err == nil && id != uuid.Nil && value == UpstreamRejectionRequestIDPrefix+id.String()
}

func (c *UpstreamRejectionReserveCommand) Validate() error {
	if c == nil || !IsUpstreamRejectionRequestID(c.RequestID) || c.UserID <= 0 || c.APIKeyID <= 0 || c.AccountID <= 0 || c.GroupID <= 0 ||
		strings.TrimSpace(c.Model) == "" || len(c.Model) > 256 || strings.TrimSpace(c.PolicyVersion) == "" || len(c.PolicyVersion) > 128 ||
		strings.TrimSpace(c.RuleVersion) == "" || len(c.RuleVersion) > 128 || !IsUpstreamRejectionProfile(c.ProviderProfile) || c.UpstreamCurrency != "USD" ||
		!validRejectionAmount(c.Price) || (c.UpstreamCost != 0 && !validRejectionAmount(c.UpstreamCost)) || len(c.RequestPayloadHash) != sha256.Size*2 || len(c.UpstreamIdentityHash) != sha256.Size*2 {
		return ErrUpstreamRejectionInvalid
	}
	if _, err := hex.DecodeString(c.RequestPayloadHash); err != nil {
		return ErrUpstreamRejectionInvalid
	}
	if _, err := hex.DecodeString(c.UpstreamIdentityHash); err != nil {
		return ErrUpstreamRejectionInvalid
	}
	return nil
}

// UpstreamRejectionIdentityHash binds a pending operation to the credential and
// endpoint that accepted it. Never persist or log the canonical input: only its
// digest belongs in the ledger. Model mappings, prices and scheduling metadata
// are deliberately excluded, so refreshing a model list does not change identity.
func UpstreamRejectionIdentityHash(account *Account) (string, error) {
	if account == nil || account.Platform != PlatformGrok || account.Type != AccountTypeAPIKey {
		return "", ErrUpstreamRejectionInvalid
	}
	key := strings.TrimSpace(account.GetCredential("api_key"))
	if key == "" {
		return "", ErrUpstreamRejectionInvalid
	}
	u, err := url.Parse(strings.TrimSpace(account.GetGrokMediaBaseURL()))
	if err != nil {
		return "", ErrUpstreamRejectionInvalid
	}
	u.Scheme = strings.ToLower(u.Scheme)
	if (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" {
		return "", ErrUpstreamRejectionInvalid
	}
	u.Host = strings.ToLower(u.Host)
	u.Path = strings.TrimRight(u.Path, "/")
	if u.RawPath != "" {
		u.RawPath = strings.TrimRight(u.RawPath, "/")
	}
	canonical := struct {
		Version  int               `json:"version"`
		Platform string            `json:"platform"`
		Type     string            `json:"type"`
		BaseURL  string            `json:"base_url"`
		APIKey   string            `json:"api_key"`
		Headers  map[string]string `json:"headers"`
	}{1, account.Platform, account.Type, u.String(), key, account.GetHeaderOverrides()}
	return rejectionFingerprint(canonical), nil
}

func validRejectionAmount(v float64) bool {
	// Use the same decimal/NUMERIC bound as Group persistence; a valid saved
	// customer price must not become invalid only when a request is admitted.
	return ValidateUpstreamRejectionBillingConfig(true, v) == nil
}

func (c *UpstreamRejectionReserveCommand) Fingerprint() string { return rejectionFingerprint(c) }

// Evidence intentionally has no free-form prompt, response, secret, or error body.
type UpstreamRejectionBillingEvidence struct {
	RuleID                string `json:"rule_id,omitempty"`
	RuleVersion           string `json:"rule_version,omitempty"`
	OriginalStatus        int    `json:"original_status,omitempty"`
	UpstreamRequestID     string `json:"upstream_request_id,omitempty"`
	ResponseDigest        string `json:"response_digest,omitempty"`
	InputTokens           int    `json:"input_tokens,omitempty"`
	OutputTokens          int    `json:"output_tokens,omitempty"`
	CacheReadTokens       int    `json:"cache_read_tokens,omitempty"`
	CacheWriteTokens      int    `json:"cache_write_tokens,omitempty"`
	OriginalModel         string `json:"original_model,omitempty"`
	UpstreamModel         string `json:"upstream_model,omitempty"`
	UpstreamResponseModel string `json:"upstream_response_model,omitempty"`
	InboundEndpoint       string `json:"inbound_endpoint,omitempty"`
	UpstreamEndpoint      string `json:"upstream_endpoint,omitempty"`
	Stream                bool   `json:"stream,omitempty"`
	DurationMs            int    `json:"duration_ms,omitempty"`
	// Empty for every release that existed before the deadline waiver.
	ReleaseReason string `json:"release_reason,omitempty"`
	// ReleasedFrom is the state a deadline release left (sent or unknown). The
	// repository writes it from the locked row; a command can never carry it.
	ReleasedFrom string `json:"released_from,omitempty"`
}

type UpstreamRejectionFinalizeCommand struct {
	RequestID string `json:"request_id"`
	APIKeyID  int64  `json:"api_key_id"`
	// Outcome is rejected, released, or unknown. Normal bills use
	// UsageBillingCommand.UpstreamRejectionReservationID for atomic release+bill.
	Outcome string `json:"outcome"`
	// Required to release a sent/unknown request. A timeout is never confirmation.
	ConfirmedNoCharge bool `json:"confirmed_no_charge,omitempty"`
	// DeadlinePassed requests the policy release of a sent/unknown synchronous
	// hold whose durable deadline has passed by the database clock. Use
	// NewUpstreamRejectionDeadlineReleaseCommand; omitted when false so the
	// fingerprints of the existing paths are unchanged.
	DeadlinePassed bool                             `json:"deadline_passed,omitempty"`
	Evidence       UpstreamRejectionBillingEvidence `json:"evidence"`
}

// NewUpstreamRejectionDeadlineReleaseCommand builds the only accepted form of
// the deadline waiver, so replays share one fingerprint.
func NewUpstreamRejectionDeadlineReleaseCommand(requestID string, apiKeyID int64) *UpstreamRejectionFinalizeCommand {
	return &UpstreamRejectionFinalizeCommand{RequestID: requestID, APIKeyID: apiKeyID, Outcome: UpstreamRejectionReleased,
		DeadlinePassed: true, Evidence: UpstreamRejectionBillingEvidence{ReleaseReason: UpstreamRejectionReleaseDeadlinePassed}}
}

// ReleasedAtDeadline reports whether the deadline waiver released this hold.
func (r *UpstreamRejectionReservation) ReleasedAtDeadline() bool {
	return r != nil && r.State == UpstreamRejectionReleased && r.Evidence.ReleaseReason == UpstreamRejectionReleaseDeadlinePassed
}

// ReleasedAtDeadlineWhileSent reports a deadline release of a hold that was
// still sent: the gateway never saw the request end, so the owning process was
// presumed dead. Only the fixed-fee reservation was given back; an ordinary
// bill that arrives later is still owed. A release from unknown follows a
// request the gateway saw end without a usable result, so nothing more is owed.
func (r *UpstreamRejectionReservation) ReleasedAtDeadlineWhileSent() bool {
	return r.ReleasedAtDeadline() && r.Evidence.ReleasedFrom == UpstreamRejectionSent
}

func (c *UpstreamRejectionFinalizeCommand) Validate() error {
	if c == nil || !IsUpstreamRejectionRequestID(c.RequestID) || c.APIKeyID <= 0 {
		return ErrUpstreamRejectionInvalid
	}
	e := c.Evidence
	if len(e.RuleID) > 128 || len(e.RuleVersion) > 128 || len(e.UpstreamRequestID) > 256 || len(e.ResponseDigest) > 64 ||
		e.InputTokens < 0 || e.OutputTokens < 0 || e.CacheReadTokens < 0 || e.CacheWriteTokens < 0 ||
		len(e.OriginalModel) > 256 || len(e.UpstreamModel) > 256 || len(e.UpstreamResponseModel) > 256 ||
		len(e.InboundEndpoint) > 256 || len(e.UpstreamEndpoint) > 256 || strings.ContainsAny(e.InboundEndpoint+e.UpstreamEndpoint, "?#\r\n") || e.DurationMs < 0 || e.DurationMs > 2147483647 {
		return ErrUpstreamRejectionInvalid
	}
	// The reason is server-owned: only the waiver may carry it, and the waiver
	// carries nothing else, so a release reason can never be forged.
	if c.DeadlinePassed {
		if c.Outcome != UpstreamRejectionReleased || c.ConfirmedNoCharge || e != (UpstreamRejectionBillingEvidence{ReleaseReason: UpstreamRejectionReleaseDeadlinePassed}) {
			return ErrUpstreamRejectionInvalid
		}
	} else if e.ReleaseReason != "" {
		return ErrUpstreamRejectionInvalid
	}
	if e.ReleasedFrom != "" {
		return ErrUpstreamRejectionInvalid
	}
	if e.ResponseDigest != "" {
		if len(e.ResponseDigest) != 64 {
			return ErrUpstreamRejectionInvalid
		}
		if _, err := hex.DecodeString(e.ResponseDigest); err != nil {
			return ErrUpstreamRejectionInvalid
		}
	}
	switch c.Outcome {
	case UpstreamRejectionRejected:
		if e.RuleID == "" || e.RuleVersion == "" || (e.OriginalStatus < 200 || e.OriginalStatus >= 300) && e.OriginalStatus != 400 && e.OriginalStatus != 403 {
			return ErrUpstreamRejectionInvalid
		}
	case UpstreamRejectionReleased, UpstreamRejectionUnknown:
	default:
		return ErrUpstreamRejectionInvalid
	}
	return nil
}

func (c *UpstreamRejectionFinalizeCommand) Fingerprint() string { return rejectionFingerprint(c) }

func rejectionFingerprint(v any) string {
	encoded, _ := json.Marshal(v)
	sum := sha256.Sum256(encoded)
	return hex.EncodeToString(sum[:])
}

type UpstreamRejectionTaskBinding struct {
	RequestID       string `json:"request_id"`
	APIKeyID        int64  `json:"api_key_id"`
	TaskID          string `json:"task_id"`
	DurationSeconds int    `json:"duration_seconds"`
	Resolution      string `json:"resolution"`
	OriginalModel   string `json:"original_model"`
	UpstreamModel   string `json:"upstream_model"`
	// Explicit per-second video pricing captured before the creation request.
	// Nil means no quote; zero is a legitimate quoted free price.
	VideoBasePricePerSecond  *float64 `json:"video_base_price_per_second,omitempty"`
	VideoFinalPricePerSecond *float64 `json:"video_final_price_per_second,omitempty"`
}

func (b *UpstreamRejectionTaskBinding) Validate() error {
	if b == nil || !IsUpstreamRejectionRequestID(b.RequestID) || b.APIKeyID <= 0 || strings.TrimSpace(b.TaskID) == "" || len(b.TaskID) > 256 || b.DurationSeconds < 0 || len(b.Resolution) > 32 || len(b.OriginalModel) > 256 || len(b.UpstreamModel) > 256 {
		return ErrUpstreamRejectionInvalid
	}
	if (b.VideoBasePricePerSecond == nil) != (b.VideoFinalPricePerSecond == nil) {
		return ErrUpstreamRejectionInvalid
	}
	for _, value := range []*float64{b.VideoBasePricePerSecond, b.VideoFinalPricePerSecond} {
		if value != nil && (*value < 0 || math.IsNaN(*value) || math.IsInf(*value, 0)) {
			return ErrUpstreamRejectionInvalid
		}
	}
	return nil
}

// Reservation is durable recovery state, including the frozen price snapshot.
type UpstreamRejectionReservation struct {
	UpstreamRejectionReserveCommand
	State                  string                           `json:"state"`
	Evidence               UpstreamRejectionBillingEvidence `json:"evidence"`
	Task                   *UpstreamRejectionTaskBinding    `json:"task,omitempty"`
	NormalBillingRequestID string                           `json:"normal_billing_request_id,omitempty"`
	CreatedAt              time.Time                        `json:"created_at"`
	UpdatedAt              time.Time                        `json:"updated_at"`
	SentAt                 *time.Time                       `json:"sent_at,omitempty"`
	UsageProjectedAt       *time.Time                       `json:"usage_projected_at,omitempty"`
	// ReleaseAfter is the durable deadline of the waiver; nil for rows created
	// before it and for task-bound rows. Excluded from JSON so the snapshots
	// written into billing events stay byte-identical.
	ReleaseAfter *time.Time `json:"-"`
}

// UpstreamRejectionLateResult is a result observed after the deadline waiver
// released the hold, stored once for supplier reconciliation. Only an ordinary
// bill after a release from sent is charged (through the ordinary path);
// everything else is recorded without charge. Evidence holds no prompt,
// response body, URL or credential.
type UpstreamRejectionLateResult struct {
	Kind string `json:"kind"`
	// BillingRequestID is the ordinary usage bill this result belongs to.
	BillingRequestID string `json:"billing_request_id,omitempty"`
	// Amount is what this result costs the customer under the normal rules.
	Amount   float64                          `json:"amount"`
	Charged  bool                             `json:"charged"`
	Evidence UpstreamRejectionBillingEvidence `json:"evidence"`
}

type UpstreamRejectionBillingResult struct {
	Applied              bool
	Reservation          *UpstreamRejectionReservation
	NewBalance           float64
	FrozenBalance        float64
	APIKeyQuotaExhausted bool
	AccountQuotaState    *AccountQuotaState
}

type UpstreamRejectionPendingCursor struct {
	UpdatedAt time.Time
	RequestID string
}

type UpstreamRejectionPendingQuery struct {
	Limit int
	After *UpstreamRejectionPendingCursor
	// Video reconcilers can exclude unknown requests that have no durable task.
	TasksOnly bool
}

type UpstreamRejectionPendingPage struct {
	Items []UpstreamRejectionReservation
	Next  *UpstreamRejectionPendingCursor
}

type UpstreamRejectionDueCursor struct {
	ReleaseAfter time.Time
	RequestID    string
}

type UpstreamRejectionDueQuery struct {
	Limit int
	After *UpstreamRejectionDueCursor
}

type UpstreamRejectionDuePage struct {
	Items []UpstreamRejectionReservation
	Next  *UpstreamRejectionDueCursor
}

// UpstreamRejectionDueSource lists synchronous holds whose release deadline
// has passed by the database clock. It is a separate optional interface so
// existing UpstreamRejectionBillingRepository implementations stay valid.
type UpstreamRejectionDueSource interface {
	ListDueUpstreamRejectionsPage(context.Context, *UpstreamRejectionDueQuery) (*UpstreamRejectionDuePage, error)
}

// This optional interface avoids changing all existing UsageBillingRepository mocks.
// All mutations are PG transactions; there is no cache or non-atomic fallback.
type UpstreamRejectionBillingRepository interface {
	ReserveUpstreamRejection(context.Context, *UpstreamRejectionReserveCommand) (*UpstreamRejectionBillingResult, error)
	MarkUpstreamRejectionSent(context.Context, string, int64) (*UpstreamRejectionBillingResult, error)
	FinalizeUpstreamRejection(context.Context, *UpstreamRejectionFinalizeCommand) (*UpstreamRejectionBillingResult, error)
	GetUpstreamRejection(context.Context, string, int64) (*UpstreamRejectionReservation, error)
	ListPendingUpstreamRejections(context.Context, int) ([]UpstreamRejectionReservation, error)
	ListPendingUpstreamRejectionsPage(context.Context, *UpstreamRejectionPendingQuery) (*UpstreamRejectionPendingPage, error)
	ListUnprojectedUpstreamRejectionsPage(context.Context, *UpstreamRejectionPendingQuery) (*UpstreamRejectionPendingPage, error)
	MarkUpstreamRejectionUsageProjected(context.Context, string, int64) error
	BindUpstreamRejectionTask(context.Context, *UpstreamRejectionTaskBinding) error
	GetUpstreamRejectionByTask(context.Context, int64, int64, string) (*UpstreamRejectionReservation, error)
}
